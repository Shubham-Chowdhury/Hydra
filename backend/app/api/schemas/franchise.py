"""Pydantic transport schemas for Franchise Agents and Simulated Auction."""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.api.schemas.student import StudentProfileRequest


class ScoringPolicyDto(BaseModel):
    """Configuration for custom scoring policy in auction requests."""

    policy_version: str = Field(default="v1.0", description="Policy identifier")
    weight_discipline: float = Field(default=0.35, ge=0.0, le=1.0)
    weight_career: float = Field(default=0.30, ge=0.0, le=1.0)
    weight_academic: float = Field(default=0.20, ge=0.0, le=1.0)
    weight_geographic: float = Field(default=0.15, ge=0.0, le=1.0)


class AuctionRequestDto(BaseModel):
    """Request payload for executing a simulated programme auction."""

    snapshot_id: Optional[str] = Field(
        default=None,
        description="ID of a previously constructed Twin snapshot.",
    )
    twin_id: Optional[str] = Field(
        default=None,
        description="ID of student Twin if retrieving most recent snapshot.",
    )
    profile: Optional[StudentProfileRequest] = Field(
        default=None,
        description="Student profile payload to construct Twin ad-hoc if snapshot not provided.",
    )
    programme_ids: Optional[List[str]] = Field(
        default=None,
        description="Optional list of specific programme IDs to participate in the auction.",
    )
    scoring_policy: Optional[ScoringPolicyDto] = Field(
        default=None,
        description="Optional customized weighting policy.",
    )


class ProgrammeBidDto(BaseModel):
    """Proposal (bid) generated by a Franchise Agent."""

    bid_id: str
    agent_id: str
    programme_id: str
    programme_title: str
    institution_name: str
    twin_id: str
    snapshot_id: str
    eligibility_status: str
    affordability_status: bool
    total_budget_inr: float
    estimated_total_tuition_inr: float
    currency: str
    cost_basis: str
    academic_alignment: float
    discipline_alignment: float
    career_alignment: float
    geographic_alignment: float
    composite_preference_score: Optional[float] = None
    evidence_coverage_ratio: float = 1.0
    active_dimensions: List[str] = Field(default_factory=list)
    is_insufficient_evidence: bool = False
    evidence_tier: str = "comprehensive"
    is_unscored: bool = False
    neutral_baseline_display: float = 0.50
    proposal_status: str
    policy_version: str
    evidence_references: List[str]
    missing_facts: List[str]
    warnings: List[str]
    reasoning_trace: Dict[str, Any]
    created_at: str
    is_synthetic: bool
    dataset_label: str


class AuctionRankingItemDto(BaseModel):
    """Ranked item within an auction result."""

    rank: int
    bid: ProgrammeBidDto
    explanation: str
    tie_breaker_applied: Optional[str] = None
    is_positive_bid: Optional[bool] = True


class AuctionResultDto(BaseModel):
    """Complete structured response bundle from a simulated programme auction."""

    auction_id: str
    twin_id: str
    snapshot_id: str
    policy_version: str
    total_bids: int
    unconditional_candidates: List[AuctionRankingItemDto]
    conditional_candidates: List[AuctionRankingItemDto]
    no_bid_candidates: List[AuctionRankingItemDto]
    ranked_bids: List[AuctionRankingItemDto]
    auction_summary: str
    executed_at: str


class FranchiseInfoDto(BaseModel):
    """Metadata for an active programme franchise agent."""

    programme_id: str
    title: str
    institution_name: str
    location: str
    discipline: str
    agent_id: str
    is_synthetic: bool
    dataset_label: str
