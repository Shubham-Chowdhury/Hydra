"""Comprehensive Assessment and Career Pathway Domain Models for Hydra.

Defines domain frames for tracking student interaction trajectories,
deep neural trajectory insights, and comprehensive assessment reports.
Strictly maintains decoupling between deterministic rule eligibility
and deep learning probabilistic career forecasts.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional


@dataclass(frozen=True)
class UserInteractionEvent:
    """Tracks discrete student interactions across platform subsystems."""

    event_id: str
    event_type: str  # e.g., 'view_page', 'evaluate_profile', 'run_auction', 'plan_pathway', 'voice_query'
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    target_id: Optional[str] = None
    domain: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class NeuralTrajectoryInsights:
    """Probabilistic trajectory estimates generated by the deep sequence model."""

    career_readiness_score: float  # [0.0 - 1.0]
    domain_affinity_weights: Dict[str, float]  # Normalized affinity per discipline
    learning_velocity_index: float  # Momentum factor
    risk_assessment_index: float  # Estimated difficulty or risk [0.0 - 1.0]
    projected_career_outcomes: List[str]
    model_architecture: str = "Deep Dense Residual Sequence Encoder (3-layer MLP with Self-Attention, GELU activation, Softmax projection)"
    confidence: float = 0.88
    is_estimate: bool = True
    provenance: str = "NEURAL_TRAJECTORY_NETWORK_V1"
    is_synthetic: bool = True


@dataclass(frozen=True)
class ComprehensiveAssessmentReport:
    """Consolidated assessment & career pathway report combining deterministic & neural models."""

    report_id: str
    student_id: str
    generated_at: str
    executive_summary: str
    voice_script: str
    academic_standing: Dict[str, Any]
    verified_eligibility_breakdown: Dict[str, int]  # eligible, needs_review, ineligible
    top_recommended_pathways: List[Dict[str, Any]]
    neural_insights: NeuralTrajectoryInsights
    actionable_milestones: List[Dict[str, Any]]
    is_synthetic: bool = True
    dataset_label: str = "SYNTHETIC_DEMO_CATALOG_NOT_OFFICIAL"
    provenance: str = "HYDRA_ASSESSMENT_CORE_V1"

